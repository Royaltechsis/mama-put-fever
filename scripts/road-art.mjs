// Shrinks the city backdrops in assets/road/src (made with docs/road-backdrop-prompts.md) to a game-friendly size and
// regenerates src/v2/roadArt.ts so the level road picks them up.
//
//   node scripts/road-art.mjs
//
// Files are named <city>-<part>, e.g. lagos-1.png and lagos-2.png; the parts are laid side by side in order.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const Jimp = require('jimp-compact');

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const SRC = path.join(ROOT, 'assets/road/src');
const OUT = path.join(ROOT, 'assets/road');
const MANIFEST = path.join(ROOT, 'src/v2/roadArt.ts');
const HEIGHT = 780; // twice the 390 stage height, sharp on high-density screens

fs.mkdirSync(SRC, { recursive: true });
const files = fs.readdirSync(SRC).filter((f) => /^[a-z]+-\d+\.(png|jpe?g)$/i.test(f));
if (files.length === 0) console.log('No backdrops in assets/road/src yet. See docs/road-backdrop-prompts.md.');
for (const f of files) {
  const img = await Jimp.read(path.join(SRC, f));
  img.resize(Jimp.AUTO, HEIGHT).quality(82);
  const name = f.replace(/\.(png|jpe?g)$/i, '.jpg').toLowerCase();
  fs.writeFileSync(path.join(OUT, name), await img.getBufferAsync(Jimp.MIME_JPEG));
  console.log(`✓ ${name} (${img.bitmap.width}x${img.bitmap.height})`);
}

const byCity = {};
const dims = {};
for (const f of fs.readdirSync(OUT).filter((x) => /^[a-z]+-\d+\.jpg$/.test(x)).sort()) {
  const [city, part] = f.slice(0, -4).split('-');
  const im = await Jimp.read(path.join(OUT, f));
  dims[f] = { w: im.bitmap.width, h: im.bitmap.height };
  (byCity[city] ??= []).push({ part: Number(part), f });
}
const lines = [
  '// Generated by scripts/road-art.mjs. Do not edit by hand.',
  '// Painted city backdrops behind each level road, laid side by side; cities without any use the drawn skyline.',
  'export const ROAD_ART: Record<string, { src: number; w: number; h: number }[]> = {',
  ...Object.entries(byCity).map(([city, parts]) => `  ${city}: [${parts.sort((a, b) => a.part - b.part).map((p) => `{ src: require('../../assets/road/${p.f}'), w: ${dims[p.f].w}, h: ${dims[p.f].h} }`).join(', ')}],`),
  '};',
  '',
];
fs.writeFileSync(MANIFEST, lines.join('\n'));
console.log(`wrote ${path.relative(ROOT, MANIFEST)} (${Object.keys(byCity).join(', ') || 'no cities yet'})`);
